"""Create a v1 training manifest from Nutrition5k dish metadata and RGB files.

Nutrition5k distributions differ in layout, so RGB files are indexed recursively
and matched by dish id. Optional geometry features can be merged from a separate
CSV generated by the volume preprocessing step.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
from pathlib import Path

from .dataset import write_manifest
from .models import NUMERIC_FEATURES


def stable_split(dish_id: str) -> str:
    bucket = int(hashlib.sha1(dish_id.encode()).hexdigest()[:8], 16) % 100
    return "train" if bucket < 80 else ("val" if bucket < 90 else "test")


def main(args: argparse.Namespace) -> None:
    root = Path(args.dataset_root)
    candidates: dict[str, Path] = {}
    for path in root.rglob("*"):
        if path.suffix.lower() in {".jpg", ".jpeg", ".png"} and "depth" not in path.name.lower():
            for part in path.parts:
                if part.startswith("dish_"):
                    candidates.setdefault(part, path)
                    break
    geometry: dict[str, dict[str, str]] = {}
    if args.geometry_csv:
        with Path(args.geometry_csv).open(newline="", encoding="utf-8") as handle:
            geometry = {row["dish_id"]: row for row in csv.DictReader(handle)}
    rows = []
    with Path(args.metadata_csv).open(newline="", encoding="utf-8") as handle:
        for values in csv.reader(handle):
            if not values or not values[0].startswith("dish_"):
                continue
            dish_id, mass = values[0], float(values[2])
            image = candidates.get(dish_id)
            if image is None or mass <= 0:
                continue
            extra = geometry.get(dish_id, {})
            tier = extra.get("tier", "monocular")
            row = {
                "image_path": str(image.relative_to(root)), "mass_g": mass,
                "volume_ml": extra.get("volume_ml", ""), "split": stable_split(dish_id),
                "dish_id": dish_id, "density_prior_g_ml": extra.get("density_prior_g_ml", 1.0),
                "tier_ar": int(tier == "ar_scan"), "tier_rgbd": int(tier == "rgbd"),
                "tier_monocular": int(tier == "monocular"),
                "has_metric_geometry": int(bool(extra.get("volume_ml"))),
            }
            for key in NUMERIC_FEATURES:
                if key in extra:
                    row[key] = extra[key]
            rows.append(row)
    write_manifest(rows, args.output)
    print(f"wrote {len(rows)} rows to {args.output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset-root", required=True)
    parser.add_argument("--metadata-csv", required=True)
    parser.add_argument("--geometry-csv")
    parser.add_argument("--output", default="nutrition5k_v1.csv")
    main(parser.parse_args())
